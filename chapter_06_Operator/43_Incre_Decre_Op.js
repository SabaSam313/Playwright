// Increment and Decrement Operator

// Pre Increment
{
    let a = 10;
    let b = ++a; // (increment the a by 1)


    // Pre increment -> ++a -> increase the value and then assign.
    console.log(b);
    console.log(a);
}

// Decrement
{
    let a = 10;
    let b = --a; // (Decrement the a by 1)


    // Pre decrement -> --a -> decrease the value and then assign.
    console.log(b);
    console.log(a);
}

// Post Decrement
{
    let a = 10;
    let b = a--; // (Decrement the a by 1)


    // Decrement -> a-- -> assign then decrease the value.
    console.log(b);
    console.log(a);
}
