// Single quote, double quote, and backtick are used to create strings.
// Main difference: backtick can use ${} to add variables inside the string.

let name = "Saba";

let singleQuote = 'Hello Jalal';
let doubleQuote = "Hello Sahera";
let backtick = `Hello ${name}`;

console.log(singleQuote);
console.log(doubleQuote);
console.log(backtick);
